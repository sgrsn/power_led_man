#!/usr/bin/env python3
"""Generate lookup tables for src/tables.c.

Run from the project root:  python3 tools/gen_tables.py > src/tables.c
"""
import math

GAMMA = 2.2


def fmt(values, per_line):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


# Perceptual level (0..255) -> linear duty (0..65535).
gamma = [round(65535 * (i / 255) ** GAMMA) for i in range(256)]

# One period of a raised cosine, 0 at index 0, 255 at index 128.
wave = [round(255 * (1 - math.cos(2 * math.pi * i / 256)) / 2) for i in range(256)]

print(f"""// Generated by tools/gen_tables.py -- do not edit by hand.
#include "tables.h"

// Perceptual level -> linear duty, gamma {GAMMA}.
const uint16_t gamma_table[256] PROGMEM = {{
{fmt(gamma, 12)}
}};

// Raised cosine: 0 at index 0, 255 at index 128.
const uint8_t wave_table[256] PROGMEM = {{
{fmt(wave, 16)}
}};""")
